"""Finding and run data models, plus the deterministic post-processing that
keeps AI output honest and repeatable:

* ``verify_location``  — the model must quote the flagged line; we check the
  quote against the real file and correct (±10 lines) or drop the finding.
* ``compute_severity`` — severity comes from a fixed formula over factors the
  Verifier reports, never from the model's free-form opinion.
* ``fingerprint``      — stable identity of an issue across runs and small
  refactors; the finding ID (ARG-XXXXXXXX) is derived from it.
* ``vote_merge``       — self-consistency: keep issues a majority of runs found.
"""

from __future__ import annotations

import hashlib
import re
from datetime import datetime, timezone
from typing import Literal

from pydantic import BaseModel, Field

from . import PROMPT_VERSION, __version__
from .config import SEVERITY_ORDER

Status = Literal["confirmed", "needs_context", "unverified", "rejected", "suppressed"]
ACTIVE_STATUSES = ("confirmed", "needs_context", "unverified")


def utcnow() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class FlowStep(BaseModel):
    file: str
    line: int
    role: Literal["source", "propagation", "sanitizer", "sink"] = "propagation"
    note: str = ""


class SeverityFactors(BaseModel):
    impact: Literal["rce", "data_breach", "privilege_escalation", "data_tamper", "dos", "info_leak", "minor"] = "minor"
    attacker_position: Literal["remote_unauthenticated", "remote_authenticated", "internal", "local"] = "remote_authenticated"
    exploitability: Literal["easy", "moderate", "hard"] = "moderate"


class Remediation(BaseModel):
    summary: str = ""
    start_line: int | None = None
    end_line: int | None = None
    fixed_code: str | None = None
    new_imports: list[str] = Field(default_factory=list)
    patch: str | None = None  # unified diff, generated by Argus (not the model)
    patch_valid: bool = False
    guidance_only: bool = True
    validation_note: str = ""
    applied: bool = False
    applied_at: str | None = None


class CodeContext(BaseModel):
    """A redacted slice of the file around the finding (for UI and re-verify)."""

    start_line: int
    lines: list[str]


class Finding(BaseModel):
    id: str = ""
    fingerprint: str = ""
    status: Status = "unverified"
    title: str
    cwe: str | None = None
    cwe_name: str = ""
    owasp: dict[str, str | None] = Field(default_factory=lambda: {"2025": None, "2021": None})
    severity: str = "medium"
    confidence: float = 0.5
    votes: str | None = None  # e.g. "3/3"
    detector: Literal["ai", "rule", "ai+rule"] = "ai"
    rule_id: str | None = None
    language: str = ""
    file: str
    start_line: int
    end_line: int
    snippet: str = ""
    function: str | None = None
    data_flow: list[FlowStep] = Field(default_factory=list)
    explanation: str = ""
    exploit_scenario: str = ""
    impact: str = ""
    context_question: str | None = None
    context_answer: str | None = None
    severity_factors: SeverityFactors | None = None
    remediation: Remediation = Field(default_factory=Remediation)
    references: list[str] = Field(default_factory=list)
    code_context: CodeContext | None = None
    suppressed_reason: str | None = None
    meta: dict = Field(default_factory=dict)

    def location(self) -> str:
        return f"{self.file}:{self.start_line}"

    def sort_key(self) -> tuple:
        status_rank = {"confirmed": 0, "needs_context": 1, "unverified": 2, "suppressed": 3, "rejected": 4}
        return (status_rank.get(self.status, 9), -severity_rank(self.severity), self.file, self.start_line, self.cwe or "")


class RunStats(BaseModel):
    files_scanned: int = 0
    files_skipped: int = 0
    lines_scanned: int = 0
    chunks: int = 0
    chunks_analysed: int = 0
    rules_loaded: int = 0
    custom_rules: int = 0
    signals: int = 0
    llm_calls: int = 0
    llm_cache_hits: int = 0
    llm_failures: int = 0
    input_tokens: int = 0
    output_tokens: int = 0
    hallucinated_lines_dropped: int = 0
    secrets_redacted: int = 0
    duration_seconds: float = 0.0


class ScanRun(BaseModel):
    id: str
    created_at: str = Field(default_factory=utcnow)
    finished_at: str | None = None
    status: Literal["queued", "running", "completed", "failed", "cancelled"] = "queued"
    phase: str = ""
    progress: float = 0.0
    target: str
    target_kind: str = ""
    target_root: str | None = None  # None once a temporary clone is deleted
    target_key: str = ""
    repo_url: str | None = None
    ref: str | None = None
    ai_enabled: bool = True
    provider: str | None = None
    model: str | None = None
    owasp_edition: str = "2025"
    argus_version: str = __version__
    prompt_version: str = PROMPT_VERSION
    settings: dict = Field(default_factory=dict)
    custom_rule_ids: list[str] = Field(default_factory=list)
    repo_context: dict = Field(default_factory=dict)
    stats: RunStats = Field(default_factory=RunStats)
    findings: list[Finding] = Field(default_factory=list)
    signals_not_flagged: list[dict] = Field(default_factory=list)
    skipped_files: list[dict] = Field(default_factory=list)
    file_hashes: dict[str, str] = Field(default_factory=dict)
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)

    def finding(self, finding_id: str) -> Finding | None:
        fid = finding_id.strip().upper()
        for f in self.findings:
            if f.id.upper() == fid or f.fingerprint.startswith(finding_id.strip().lower()):
                return f
        return None

    def active_findings(self) -> list[Finding]:
        return [f for f in self.findings if f.status in ACTIVE_STATUSES]

    def counts(self) -> dict:
        by_sev = {s: 0 for s in reversed(SEVERITY_ORDER)}
        by_status: dict[str, int] = {}
        for f in self.findings:
            by_status[f.status] = by_status.get(f.status, 0) + 1
            if f.status in ACTIVE_STATUSES:
                by_sev[f.severity] = by_sev.get(f.severity, 0) + 1
        return {"by_severity": by_sev, "by_status": by_status}


# --------------------------------------------------------------------------- #
# Severity
# --------------------------------------------------------------------------- #
_IMPACT_BASE = {
    "rce": 9.0,
    "data_breach": 8.0,
    "privilege_escalation": 8.0,
    "data_tamper": 7.0,
    "dos": 5.0,
    "info_leak": 4.0,
    "minor": 2.0,
}
_POSITION_MOD = {"remote_unauthenticated": 1.0, "remote_authenticated": 0.0, "internal": -1.0, "local": -2.0}
_EXPLOIT_MOD = {"easy": 0.5, "moderate": 0.0, "hard": -1.5}


def compute_severity(f: SeverityFactors) -> str:
    """Deterministic: identical factors always give identical severity."""
    score = _IMPACT_BASE[f.impact] + _POSITION_MOD[f.attacker_position] + _EXPLOIT_MOD[f.exploitability]
    score = max(0.0, min(10.0, score))
    if score >= 9.0:
        return "critical"
    if score >= 7.0:
        return "high"
    if score >= 4.0:
        return "medium"
    if score >= 2.0:
        return "low"
    return "info"


def severity_rank(sev: str) -> int:
    return SEVERITY_ORDER.index(sev) if sev in SEVERITY_ORDER else 0


# --------------------------------------------------------------------------- #
# Fingerprints & IDs
# --------------------------------------------------------------------------- #
_WS = re.compile(r"\s+")


def normalise_code(s: str) -> str:
    return _WS.sub(" ", s).strip()


def fingerprint(file: str, cwe: str | None, function: str | None, line_text: str) -> str:
    """Hash of WHAT the issue is, not WHERE it is: moving code up or down does
    not change it, editing the vulnerable line does."""
    payload = "|".join([file, cwe or "", function or "", normalise_code(line_text)])
    return hashlib.sha256(payload.encode("utf-8", "replace")).hexdigest()


def finding_id(fp: str) -> str:
    return "ARG-" + fp[:8].upper()


# --------------------------------------------------------------------------- #
# Line verification (anti-hallucination)
# --------------------------------------------------------------------------- #
def _first_code_line(evidence: str) -> str:
    for ln in evidence.splitlines():
        # Models sometimes copy the "  42 | " prefix; strip it.
        ln = re.sub(r"^\s*\d+\s*\|\s?", "", ln)
        if ln.strip():
            return ln
    return ""


def verify_location(
    lines: list[str], reported_line: int, evidence: str, lo: int = 1, hi: int | None = None, radius: int = 10
) -> int | None:
    """Return the corrected 1-based line where `evidence` really is, or None.

    `lines` must be the same text the model saw (i.e. the redacted lines).
    The search is confined to [lo, hi] (the chunk the model was shown).
    """
    hi = hi or len(lines)
    needle = normalise_code(_first_code_line(evidence))
    if len(needle) < 3:
        return None

    def matches(ln: int) -> bool:
        if not (lo <= ln <= hi):
            return False
        hay = normalise_code(lines[ln - 1])
        return bool(hay) and (needle in hay or (len(hay) >= 8 and hay in needle))

    if matches(reported_line):
        return reported_line
    for d in range(1, radius + 1):
        for cand in (reported_line - d, reported_line + d):
            if matches(cand):
                return cand
    # Last resort: unique match anywhere in the shown range.
    found = [ln for ln in range(lo, hi + 1) if matches(ln)]
    return found[0] if len(found) == 1 else None


# --------------------------------------------------------------------------- #
# Voting / de-duplication
# --------------------------------------------------------------------------- #
def same_issue(a_file: str, a_line: int, a_cwe: str | None, b_file: str, b_line: int, b_cwe: str | None, tol: int = 2) -> bool:
    return a_file == b_file and abs(a_line - b_line) <= tol and (a_cwe or "") == (b_cwe or "")


def vote_merge(runs: list[list[dict]], votes: int) -> list[tuple[dict, int]]:
    """`runs[i]` = verified candidate dicts from vote i (keys: file, line, cwe).
    Returns (representative, count) for clusters seen by a strict majority."""
    clusters: list[tuple[dict, set[int]]] = []
    for vi, cands in enumerate(runs):
        for c in cands:
            for rep, seen in clusters:
                if same_issue(rep["file"], rep["line"], rep["cwe"], c["file"], c["line"], c["cwe"]):
                    seen.add(vi)
                    break
            else:
                clusters.append((c, {vi}))
    need = votes // 2 + 1
    return [(rep, len(seen)) for rep, seen in clusters if len(seen) >= need]
